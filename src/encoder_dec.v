// =============================================================================
// encoder_dec.v —— 光电编码器 AB 相四倍频解码 + 里程/方向计数
// -----------------------------------------------------------------------------
// 功能：把两路正交脉冲（A/B 相，光电编码器输出）解码成：
//       * step          —— 每个四分之一线数输出 1 个 clk 宽脉冲（4 倍频）
//       * direction     —— 1=正转（B 相先翻），0=反转；无跳变时保持上次有效方向
//       * position[31:0]—— 累计里程（二补码，正转 ++ 反转 --）
//
// 状态机法（不是边沿计数法）：把 {A,B} 的历史值和当前值拼成 4 位码查表，
// 一次只允许一相跳变；同时跳两相（毛刺/丢步）视为非法，保持原值不动。
// 4 倍频 = 每个编码器线数产生 4 个 step，分辨率足够 PID 与入库停准。
//
// 【为什么 5 个输出都要有】PID / 里程积分需要的不只是 position：
//   - step  做"测速窗口内脉冲计数"（每 10 ms 数一次 = 速度）
//   - direction 给速度符号
// position 只在需要绝对里程（入库、绕障回线）时用。
//
// 输入在 clk 域用两级触发器同步，异步输入不产生亚稳态传播。
// =============================================================================
`timescale 1ns/1ns

module encoder_dec (
    input  wire        clk,       // 24 MHz
    input  wire        rst_n,     // 低有效（已同步化）
    input  wire        a,         // A 相（ enc_la / enc_ra ）
    input  wire        b,         // B 相（ enc_lb / enc_rb ）
    output wire        step,      // 1 clk 宽的"走了一格"脉冲
    output wire        direction, // 1=正转（B 相先翻）
    output reg  [31:0] position   // signed 里程累计（复位清零）
);

    // ------------------------------------------------------------------
    // 两级同步，消除亚稳态
    // ------------------------------------------------------------------
    reg [1:0] a_sync, b_sync;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) begin
            a_sync <= 2'b00;
            b_sync <= 2'b00;
        end else begin
            a_sync <= {a_sync[0], a};
            b_sync <= {b_sync[0], b};
        end

    wire a_q = a_sync[1];
    wire b_q = b_sync[1];

    // ------------------------------------------------------------------
    // 上一拍状态
    // ------------------------------------------------------------------
    reg a_prev, b_prev;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) begin
            a_prev <= 1'b0;
            b_prev <= 1'b0;
        end else begin
            a_prev <= a_q;
            b_prev <= b_q;
        end

    // ------------------------------------------------------------------
    // 四倍频译码（纯组合，连续赋值，不推断锁存器）
    // 格雷码合法序列：00 -> 01 -> 11 -> 10 -> 00（B 先翻，正转，1 个 count/边沿）
    //                00 -> 10 -> 11 -> 01 -> 00（A 先翻，反转）
    // 其余（一次跳两相）视为抖动，step=0，计数不动。
    // ------------------------------------------------------------------
    wire [3:0] ab = {a_prev, b_prev, a_q, b_q};

    wire step_fwd = (ab == 4'b00_01) | (ab == 4'b01_11) |
                    (ab == 4'b11_10) | (ab == 4'b10_00);
    wire step_rev = (ab == 4'b00_10) | (ab == 4'b10_11) |
                    (ab == 4'b11_01) | (ab == 4'b01_00);

    assign step = step_fwd | step_rev;

    // ------------------------------------------------------------------
    // 方向：只在有效跳变时更新，静止时保持（避免 PID 读到 0 抖动）
    // ------------------------------------------------------------------
    reg dir_r;
    always @(posedge clk or negedge rst_n)
        if (!rst_n)      dir_r <= 1'b1;
        else if (step_fwd) dir_r <= 1'b1;
        else if (step_rev) dir_r <= 1'b0;

    assign direction = dir_r;

    // ------------------------------------------------------------------
    // 里程累计
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n)
        if (!rst_n)           position <= 32'd0;
        else if (step_fwd)    position <= position + 32'd1;
        else if (step_rev)    position <= position - 32'd1;

endmodule
