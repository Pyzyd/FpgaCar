// =============================================================================
// oled_glyph.v —— 5x7 ASCII 点阵 ROM（oled_driver 文本行与 tb 共用同一份）
// -----------------------------------------------------------------------------
// 编码：每字形 40 位 = 5 列 x 8 位；低位字节 = 最左列，字节内 bit0 = 最上行，
//       bit7 恒 0（只画 7 行）。例：'A' = 40'h7E1111117E。
// 只收调试行真正用到的字符：A/B/C/D/E/F/G/H/I/K/L/M/N/O/P/R/S/T/U、0-9、
//       ':' '+' '-' ' '。未收录的字符输出 0（整格空白）。
// 单独成模块的理由：tb 要逐字节重建期望显存，必须与 DUT 用同一份字模，
// 否则两边各抄一份，抄错一处就变成『两边一致地错』。
// =============================================================================
`timescale 1ns/1ns

module oled_glyph (
    input  wire [7:0]  ch,      // ASCII 字符
    output reg  [39:0] glyph    // 5 列 x 8 行的列式点阵
);
    always @(*) begin
        case (ch)
        8'h20: glyph = 40'h0000000000;   // ' '
        8'h2B: glyph = 40'h08083E0808;   // '+'
        8'h2D: glyph = 40'h0808080808;   // '-'
        8'h30: glyph = 40'h3E4549513E;   // '0'
        8'h31: glyph = 40'h00407F4200;   // '1'
        8'h32: glyph = 40'h4649516142;   // '2'
        8'h33: glyph = 40'h314B454121;   // '3'
        8'h34: glyph = 40'h107F121418;   // '4'
        8'h35: glyph = 40'h3945454527;   // '5'
        8'h36: glyph = 40'h3049494A3C;   // '6'
        8'h37: glyph = 40'h0305097101;   // '7'
        8'h38: glyph = 40'h3649494936;   // '8'
        8'h39: glyph = 40'h1E29494906;   // '9'
        8'h3A: glyph = 40'h0000240000;   // ':'
        8'h41: glyph = 40'h7E1111117E;   // 'A'
        8'h42: glyph = 40'h364949497F;   // 'B'
        8'h43: glyph = 40'h224141413E;   // 'C'
        8'h44: glyph = 40'h3E4141417F;   // 'D'
        8'h45: glyph = 40'h414949497F;   // 'E'
        8'h46: glyph = 40'h010909097F;   // 'F'
        8'h47: glyph = 40'h3A4949413E;   // 'G'
        8'h48: glyph = 40'h7F0808087F;   // 'H'
        8'h49: glyph = 40'h00417F4100;   // 'I'
        8'h4B: glyph = 40'h412214087F;   // 'K'
        8'h4C: glyph = 40'h404040407F;   // 'L'
        8'h4D: glyph = 40'h7F020C027F;   // 'M'
        8'h4E: glyph = 40'h7F1008047F;   // 'N'
        8'h4F: glyph = 40'h3E4141413E;   // 'O'
        8'h50: glyph = 40'h060909097F;   // 'P'
        8'h52: glyph = 40'h462919097F;   // 'R'
        8'h53: glyph = 40'h3249494926;   // 'S'
        8'h54: glyph = 40'h01017F0101;   // 'T'
        8'h55: glyph = 40'h3F4040403F;   // 'U'
        8'h59: glyph = 40'h0304780403;   // 'Y'
        default: glyph = 40'd0;
        endcase
    end
endmodule
